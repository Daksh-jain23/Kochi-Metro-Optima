def run_test():
    df = pd.DataFrame(TRAIN_DATA_MATRIX, columns=FEATURE_COLUMNS)
    train_ids = [f"TRAIN_{i:02d}" for i in range(1, 26)]
    
    # Load Top-3 SLSQP Ensemble
    bundle = joblib.load("ml/models/method-1_constrained_slsqp/ensemble_slsqp_t3.joblib")
    
    preds = []
    for name in bundle['model_names']:
        m = bundle['base_models'][name]
        cols = list(m.feature_names_in_) if hasattr(m, 'feature_names_in_') else FEATURE_COLUMNS
        preds.append(m.predict(df[cols]))
        
    P = np.column_stack(preds)
    w = np.array([bundle['weights'][m] for m in bundle['model_names']])
    forecast_scores = P @ w
    
    res = pd.DataFrame({
        'train_id': train_ids,
        'forecast_score': np.round(forecast_scores, 4),
        'current_score': df['maintenance_priority_score']
    }).sort_values('forecast_score', ascending=False).reset_index(drop=True)
    
    res['rank'] = np.arange(1, 26)
    res['status'] = ['CRITICAL: Depot' if r <= 3 else ('INSPECTION: Bay' if r <= 5 else 'ACTIVE SERVICE') for r in res['rank']]
    
    print("=" * 75)
    print("      KOCHI METRO: 25-TRAIN PRIORITY INFERENCE (TOP-3 ENSEMBLE t+3)     ")
    print("=" * 75)
    print(f"{'Rank':<6} | {'Train ID':<9} | {'Forecast (t+3)':<14} | {'Current (t)':<12} | {'Depot Action':<18}")
    print("-" * 75)
    for _, r in res.iterrows():
        print(f"Rank {r['rank']:<2} | {r['train_id']:<9} | {r['forecast_score']:<14.4f} | {r['current_score']:<12.4f} | {r['status']:<18}")
    print("=" * 75)

if __name__ == '__main__':
    run_test()

